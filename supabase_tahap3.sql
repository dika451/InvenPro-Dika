-- InvenPro Tahap 3: transaksi stok masuk/keluar.
-- Jalankan sekali melalui Supabase Dashboard > SQL Editor > New query.
-- Aman untuk data barang yang sudah ada: tidak menghapus atau mengubah struktur tabel barang.

create table if not exists public.transaksi_stok (
  id bigint generated by default as identity primary key,
  barang_id bigint null references public.barang(id) on delete set null,
  nama_barang text not null,
  jenis text not null check (jenis in ('masuk', 'keluar')),
  jumlah integer not null check (jumlah > 0),
  keterangan text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);

create index if not exists idx_transaksi_stok_created_at
  on public.transaksi_stok (created_at desc);
create index if not exists idx_transaksi_stok_barang_id
  on public.transaksi_stok (barang_id);

alter table public.transaksi_stok enable row level security;

drop policy if exists "transaksi_stok_select_authenticated" on public.transaksi_stok;
create policy "transaksi_stok_select_authenticated"
  on public.transaksi_stok for select to authenticated
  using (true);

drop policy if exists "transaksi_stok_insert_authenticated" on public.transaksi_stok;
create policy "transaksi_stok_insert_authenticated"
  on public.transaksi_stok for insert to authenticated
  with check (true);

grant select, insert on public.transaksi_stok to authenticated;
grant usage, select on sequence public.transaksi_stok_id_seq to authenticated;

-- Fungsi ini mengunci baris barang selama perhitungan agar dua transaksi bersamaan
-- tidak menyebabkan stok menjadi salah. Perubahan stok dan pencatatan riwayat
-- berlangsung dalam satu transaksi database.
create or replace function public.proses_transaksi_stok(
  p_barang_id bigint,
  p_jenis text,
  p_jumlah integer,
  p_keterangan text default null
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_barang public.barang%rowtype;
  v_stok_baru bigint;
  v_transaksi_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Silakan login terlebih dahulu.';
  end if;
  if p_jenis not in ('masuk', 'keluar') then
    raise exception 'Jenis transaksi harus masuk atau keluar.';
  end if;
  if p_jumlah is null or p_jumlah <= 0 then
    raise exception 'Jumlah transaksi harus lebih dari 0.';
  end if;

  select * into v_barang
  from public.barang
  where id = p_barang_id
  for update;

  if not found then
    raise exception 'Barang tidak ditemukan.';
  end if;

  if p_jenis = 'masuk' then
    v_stok_baru := coalesce(v_barang.stok, 0)::bigint + p_jumlah;
  else
    if coalesce(v_barang.stok, 0) < p_jumlah then
      raise exception 'Stok tidak mencukupi. Stok tersedia: %.', coalesce(v_barang.stok, 0);
    end if;
    v_stok_baru := coalesce(v_barang.stok, 0)::bigint - p_jumlah;
  end if;

  update public.barang set stok = v_stok_baru where id = p_barang_id;

  insert into public.transaksi_stok
    (barang_id, nama_barang, jenis, jumlah, keterangan, created_by)
  values
    (p_barang_id, v_barang.nama, p_jenis, p_jumlah, nullif(trim(p_keterangan), ''), auth.uid())
  returning id into v_transaksi_id;

  return v_transaksi_id;
end;
$$;

grant execute on function public.proses_transaksi_stok(bigint, text, integer, text) to authenticated;
